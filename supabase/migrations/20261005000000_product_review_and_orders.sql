alter table public.products
  add column if not exists motif text not null default '',
  add column if not exists size text not null default '',
  add column if not exists material text not null default '',
  add column if not exists stock integer not null default 0,
  add column if not exists status text not null default 'pending',
  add column if not exists review_note text,
  add column if not exists updated_at timestamptz not null default now();

update public.products
set status = 'approved', stock = 20
where seller_id is null;

update public.products
set status = 'pending'
where seller_id is not null;

create index if not exists products_status_idx on public.products(status);

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'products_status_check'
      and conrelid = 'public.products'::regclass
  ) then
    alter table public.products
      add constraint products_status_check
      check (status in ('pending', 'approved', 'needs_revision'));
  end if;
  if not exists (
    select 1 from pg_constraint
    where conname = 'products_stock_check'
      and conrelid = 'public.products'::regclass
  ) then
    alter table public.products
      add constraint products_stock_check check (stock >= 0);
  end if;
end;
$$;

create or replace function public.force_product_pending()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.status := 'pending';
  new.review_note := null;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists products_start_pending on public.products;
create trigger products_start_pending
before insert on public.products
for each row execute procedure public.force_product_pending();

